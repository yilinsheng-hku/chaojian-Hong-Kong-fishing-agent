import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../dashboard.js',import.meta.url),'utf8');
const document={getElementById:()=>({addEventListener(){}}),querySelectorAll:()=>[]};
const {formatAnswer,validObservation}=new Function('document',source+'\nreturn {formatAnswer,validObservation};')(document);
const formatted=formatAnswer('### 当前环境\n- **风速** 12 km/h\n\n[天文台](https://www.hko.gov.hk/)');
assert.match(formatted,/<h4>当前环境<\/h4>/);
assert.match(formatted,/<ul><li><strong>风速<\/strong>/);
assert.match(formatted,/href="https:\/\/www.hko.gov.hk\/"/);
const malicious=formatAnswer('<img src=x onerror=alert(1)>\n[x](javascript:alert)\n[x](data:text/html,hello)');
assert.ok(!malicious.includes('<img'));
assert.ok(!malicious.includes('href='));
assert.ok(malicious.includes('&lt;img'));
const now=Date.now(),row={at:new Date(now).toISOString(),value:0};
assert.equal(validObservation(row,'value',90,now),true);
assert.equal(validObservation({...row,value:null},'value',90,now),false);
assert.equal(validObservation({...row,missing:true},'value',90,now),false);
assert.equal(validObservation({...row,at:new Date(now-91*60000).toISOString()},'value',90,now),false);
assert.equal(validObservation({...row,at:new Date(now+6*60000).toISOString()},'value',90,now),false);
console.log('UI: safe answer links, escaped markup, missing/zero values and observation freshness passed.');
